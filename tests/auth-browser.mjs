// Kiểm thử tùy chọn với Chrome local; driver nằm ngoài dependencies của dự án.
import { fileURLToPath } from 'node:url';
import { mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const base=process.env.AUTH_BASE_URL || 'http://127.0.0.1:3180';
const evidence=resolve(process.env.AUTH_EVIDENCE_DIR || '/tmp/it3180-auth-evidence');
mkdirSync(evidence,{recursive:true});
const database=fileURLToPath(new URL('../prisma/dev.db',import.meta.url));
const email=`browser-${randomUUID()}@example.test`;
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH || '/usr/bin/google-chrome',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const context=await browser.newContext({viewport:{width:1280,height:900}});
const page=await context.newPage();
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(/hydration|hydrated/i.test(message.text())) errors.push(message.text());});
try {
  await page.goto(base+'/register');
  await page.getByLabel('Họ và tên').fill('Thành viên kiểm thử');
  await page.getByLabel('Email',{exact:true}).fill(email);
  await page.getByLabel('Mật khẩu',{exact:true}).fill('BrowserTest123!');
  await page.getByLabel('Số điện thoại',{exact:false}).fill('--------');
  let requests=0;
  page.on('request',request=>{if(request.url().endsWith('/api/auth/register')) requests++;});
  await page.getByRole('button',{name:'Đăng ký',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'8–15 chữ số'}).waitFor();
  assert.equal(requests,0);
  console.log('PASS invalid phone blocked by form before HTTP request');
  await page.screenshot({path:resolve(evidence,'register-invalid-phone.png'),fullPage:true,caret:'initial'});
  await page.getByLabel('Số điện thoại',{exact:false}).fill('+84 912 345 678');
  await page.getByRole('button',{name:'Đăng ký',exact:true}).click();
  await page.waitForURL(base+'/listings');
  const cookie=(await context.cookies()).find(cookie=>cookie.name==='electroswap_session');
  assert.ok(cookie?.httpOnly);
  assert.equal(cookie.sameSite,'Lax');
  assert.ok(!(await page.evaluate(()=>document.cookie)).includes('electroswap_session'));
  const me=await page.evaluate(async()=>{const r=await fetch('/api/auth/me');return {status:r.status,body:await r.json()};});
  assert.equal(me.status,200);
  assert.equal(me.body.data.phone,'+84 912 345 678');
  assert.ok(!('passwordHash' in me.body.data));
  console.log('PASS registration, redirect, HttpOnly cookie, me and stored phone');
  await page.goto(base+'/profile');
  await page.reload();
  await page.getByText(email,{exact:true}).waitFor();
  await page.screenshot({path:resolve(evidence,'profile-desktop.png'),fullPage:true,caret:'initial'});
  await page.getByRole('button',{name:'Đăng xuất',exact:true}).click();
  await page.waitForURL(base+'/login');
  assert.ok(!(await context.cookies()).some(cookie=>cookie.name==='electroswap_session'));
  await page.goto(base+'/profile');
  await page.waitForURL(base+'/login');
  console.log('PASS reload preserves session; logout removes cookie and protects profile');
  await page.getByLabel('Email',{exact:true}).fill(email);
  await page.getByLabel('Mật khẩu',{exact:true}).fill('incorrect-password');
  await page.getByRole('button',{name:'Đăng nhập',exact:true}).click();
  await page.getByRole('alert').filter({hasText:'Email hoặc mật khẩu không đúng.'}).waitFor();
  assert.equal(new URL(page.url()).pathname,'/login');
  console.log('PASS incorrect credentials displayed inline');
  await page.getByLabel('Mật khẩu',{exact:true}).fill('BrowserTest123!');
  await page.getByRole('button',{name:'Đăng nhập',exact:true}).click();
  await page.waitForURL(base+'/listings');
  console.log('PASS subsequent correct login');
  await page.goto(base+'/profile');
  await page.getByRole('button',{name:'Đăng xuất',exact:true}).click();
  await page.waitForURL(base+'/login');
  await page.setViewportSize({width:375,height:812});
  await page.screenshot({path:resolve(evidence,'login-mobile.png'),fullPage:true,caret:'initial'});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.goto(base+'/register');
  await page.screenshot({path:resolve(evidence,'register-mobile.png'),fullPage:true,caret:'initial'});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  console.log('PASS login/register at 375px without horizontal overflow');
  assert.deepEqual(errors,[]);
  console.log('PASS no uncaught browser exceptions');
} finally {
  await browser.close();
  execFileSync('python3',['-c',"import sqlite3,sys; c=sqlite3.connect(sys.argv[1]); c.execute('DELETE FROM users WHERE email = ?', (sys.argv[2],)); c.commit(); c.close()",database,email]);
}
